#!/usr/bin/env python3
"""Generate exact stopping sums for all supported Q16 motion profiles."""
from pathlib import Path
VELOCITIES = (6554, 13107, 32768, 65536, 131072, 262144, 458752, 655360)
ACCELERATIONS = (33, 66, 131, 328, 655, 1311, 3277, 6554)

def render():
    lines = ['// Generated by scripts/generate_plan_lut.py; do not edit.',
             'function [19:0] profile_velocity;', '    input [2:0] code;', '    begin case (code)']
    lines += [f"        3'd{i}: profile_velocity = 20'd{v};" for i,v in enumerate(VELOCITIES)]
    lines += ['    endcase end', 'endfunction', 'function [12:0] profile_acceleration;',
              '    input [2:0] code;', '    begin case (code)']
    lines += [f"        3'd{i}: profile_acceleration = 13'd{v};" for i,v in enumerate(ACCELERATIONS)]
    lines += ['    endcase end', 'endfunction', '// Stop sums above every legal move are rejected with a 29-bit sentinel.',
              'function [28:0] profile_stopping;',
              '    input [5:0] code;', '    begin case (code)']
    for a,accel in enumerate(ACCELERATIONS):
        for v,speed in enumerate(VELOCITIES):
            # Independent finite sum, avoiding the RTL's recurrence or a
            # quotient/product formula when producing the ROM truth table.
            stopping = sum(range(speed, 0, -accel))
            assert stopping < 2**33
            # A selected speed must stop within remaining <=8191*65536.
            # The sentinel exceeds that bound, preserving every decision.
            stopping = min(stopping, 2**29 - 1)
            assert stopping <= 2**29 - 1
            lines.append(f"        6'd{8*a+v}: profile_stopping = 29'd{stopping};")
    lines += ['    endcase end', 'endfunction', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    (Path(__file__).resolve().parents[1] / 'src' / 'plan_lut.vh').write_text(render())
