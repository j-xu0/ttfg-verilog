#!/usr/bin/env python3
"""Generate the Q11 acceleration lookup for the integrated motion planner."""
from pathlib import Path

ACCELERATIONS = (1, 2, 4, 10, 20, 41, 102, 205)
# The serial engine needs the operand one bit at a time, so the lookup is only
# as wide as the largest entry. Keep this derived, not hand-tuned: every extra
# output bit becomes another stage of the bit-select mux in the engine.
ACCEL_BITS = max(1, max(ACCELERATIONS).bit_length())


def render():
    lines = ['// Generated by scripts/generate_plan_lut.py; do not edit.',
             f'localparam integer ACCEL_BITS = {ACCEL_BITS};',
             f'function [ACCEL_BITS-1:0] profile_acceleration;',
             '    input [2:0] code;', '    begin case (code)']
    lines += [f"        3'd{i}: profile_acceleration = {ACCEL_BITS}'d{v};"
              for i, v in enumerate(ACCELERATIONS)]
    lines += ['    endcase end', 'endfunction', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    (Path(__file__).resolve().parents[1] / 'src' / 'plan_lut.vh').write_text(render())
